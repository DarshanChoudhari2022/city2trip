create table if not exists public.content (
  id text primary key,
  slug text not null unique,
  kind text not null,
  payload jsonb not null,
  updated_at timestamptz not null default now(),
  position bigint generated by default as identity
);

create table if not exists public.settings (
  id text primary key,
  payload jsonb not null
);

create table if not exists public.attempts (
  id text primary key,
  count integer not null,
  expires bigint not null
);

alter table public.content enable row level security;
alter table public.settings enable row level security;
alter table public.attempts enable row level security;
grant usage on schema public to service_role;
grant select, insert, update, delete on public.content, public.settings, public.attempts to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.increment_attempt(attempt_id text, expires_at bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  attempt_count integer;
begin
  delete from public.attempts where expires < floor(extract(epoch from now()) * 1000);
  insert into public.attempts as current_attempts (id, count, expires)
  values (attempt_id, 1, expires_at)
  on conflict (id) do update
    set count = current_attempts.count + 1,
        expires = excluded.expires
  returning count into attempt_count;
  return attempt_count;
end;
$$;

revoke all on function public.increment_attempt(text, bigint) from public, anon, authenticated;
grant execute on function public.increment_attempt(text, bigint) to service_role;

